const { cmd } = require('../command');
const axios = require('axios');

cmd({
    pattern: "weather",
    alias: ["climate", "කාලගුණය"],
    desc: "ඕනෑම නගරයක වත්මන් කාලගුණ තොරතුරු ලබා ගැනීම.",
    category: "main",
    filename: __filename
},
async (conn, mek, from, options) => {
    try {
        // 'from' JID අගය නිවැරදිව String එකක් බවට පත් කර ගැනීම
        const targetJid = typeof from === 'string' ? from : (mek.key.remoteJid || String(from));
        
        // පරිශීලකයා ඇතුළත් කළ නගරයේ නම ලබා ගැනීම (උදා: .weather Colombo)
        const args = options.args;
        if (!args || args.length === 0) {
            return await conn.sendMessage(targetJid, { text: "⚠️ කරුණාකර නගරයක නමක් ඇතුළත් කරන්න!\n\n*උදාහරණ:* `.weather Colombo` හෝ `.weather Kandy`" }, { quoted: mek });
        }

        const city = args.join(" ");
        
        // නොමිලේ කාලගුණ තොරතුරු ලබාදෙන පොදු API එකක් භාවිතා කිරීම
        const response = await axios.get(`https://wttr.in{encodeURIComponent(city)}?format=j1`);
        const weatherData = response.data;

        // අවශ්‍ය තොරතුරු වෙන් කර ගැනීම
        const currentCondition = weatherData.current_condition[0];
        const tempC = currentCondition.temp_C;
        const tempF = currentCondition.temp_F;
        const humidity = currentCondition.humidity;
        const windSpeed = currentCondition.windspeedKmph;
        const weatherDesc = currentCondition.weatherDesc[0].value;
        const observationTime = currentCondition.observation_time;

        // නගරයේ නම නිවැරදිව ලබා ගැනීම
        const areaName = weatherData.nearest_area[0].areaName[0].value;
        const country = weatherData.nearest_area[0].country[0].value;

        // මැසේජ් එක ලස්සනට Format කිරීම
        const weatherMessage = `*🌤️ DENETH-MD WEATHER REPORT 🌤️*

📍 *Location:* ${areaName}, ${country}
🌡️ *Temperature:* ${tempC}°C (${tempF}°F)
☁️ *Condition:* ${weatherDesc}
💧 *Humidity:* ${humidity}%
💨 *Wind Speed:* ${windSpeed} Km/h
🕒 *Updated Time:* ${observationTime}

> *Generated by DENETH-MD* 🚀`;

        // කාලගුණ තොරතුරු වට්සැප් මැසේජ් එකක් ලෙස යැවීම
        await conn.sendMessage(targetJid, { text: weatherMessage }, { quoted: mek });

    } catch (e) {
        console.log("Weather Command Error: ", e);
        const targetJid = typeof from === 'string' ? from : (mek.key.remoteJid || String(from));
        await conn.sendMessage(targetJid, { text: "❌ එම නගරය සොයා ගැනීමට නොහැකි වුණා. කරුණාකර ඉංග්‍රීසි අකුරින් නම නිවැරදිව ඇතුළත් කරන්න. (උදා: Galle, Jaffna)" }, { quoted: mek });
    }
});
