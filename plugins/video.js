const { cmd, commands } = require("../command");
const yts = require("yt-search");
const axios = require("axios");
const config = require("../config");

cmd(
  {
    pattern: "video",
    alias: ["playvideo", "ytmp4"],
    react: "🎬",
    desc: "Download YouTube videos as MP4 format.",
    category: "download",
    filename: __filename,
  },
  async (
    danuwa,
    mek,
    m,
    {
      from,
      quoted,
      body,
      isCmd,
      command,
      args,
      q,
      isGroup,
      sender,
      senderNumber,
      botNumber2,
      botNumber,
      pushname,
      isMe,
      isOwner,
      groupMetadata,
      groupName,
      participants,
      groupAdmins,
      isBotAdmins,
      isAdmins,
      reply,
    }
  ) => {
    try {
      if (!q) return reply("⚠️ *Please provide a video name or a YouTube link!*");

      const targetJid = typeof from === 'string' ? from : (mek.key.remoteJid || String(from));

      // 1. වීඩියෝව සෙවීම ආරම්භ කිරීම
      const loadingMsg = await danuwa.sendMessage(targetJid, { 
        text: `🎬 *DENETH-MD Searching Your Video...*\n\`"${q}"\`` 
      }, { quoted: mek });

      const search = await yts(q);
      if (!search.videos || search.videos.length === 0) {
        return await danuwa.sendMessage(targetJid, { text: "❌ *Video not found! Please check the name and try again.*", edit: loadingMsg.key });
      }
      
      const data = search.videos[0];
      const url = data.url;

      // වීඩියෝ විස්තර Format කිරීම
      let desc = `*🎬 DENETH-MD VIDEO DOWNLOADER 🎬*

🎬 *Title:* ${data.title}
⏱️ *Duration:* ${data.timestamp}
📅 *Uploaded:* ${data.ago}
👀 *Views:* ${data.views.toLocaleString()}
🔗 *URL:* ${data.url}

> *Downloading your MP4 video... Please wait!* ⏳`;

      await danuwa.sendMessage(targetJid, { text: `✅ *Video Found! Sending details...*` }, { edit: loadingMsg.key });
      
      // නෙව්ස්ලෙටර් සහ ෆෝවර්ඩ් සෙටින්ග්ස්
      const newsletterContext = {
        mentionedJid: sender ? [sender] : [],
        forwardingScore: 1000,
        isForwarded: true,
        forwardedNewsletterMessageInfo: {
          newsletterJid: "120363429118791328@newsletter",
          newsletterName: "DENETH 𝐌𝐃",
          serverMessageId: 143,
        },
      };

      // විස්තර පත්‍රිකාව ලස්සන කොළ පාට Logo එක සමඟ යැවීම
      await danuwa.sendMessage(
        targetJid,
        { 
          image: { url: "https://ibb.co" }, // ඔයා එවපු අලුත්ම Logo එක
          caption: desc,
          contextInfo: newsletterContext
        },
        { quoted: mek }
      );

      // 2. 100% ක්‍රියාකාරී පොදු API එකකින් වීඩියෝව ඩවුන්ලෝඩ් කිරීම
      const apiUrl = `https://dreaded.site{encodeURIComponent(url)}`;
      const apiResponse = await axios.get(apiUrl);

      if (!apiResponse.data || !apiResponse.data.result || !apiResponse.data.result.downloadUrl) {
        return reply("❌ *Failed to fetch download link from API. Please try again later.*");
      }

      const downloadUrl = apiResponse.data.result.downloadUrl;

      // 3. වට්සැප් එකට වීඩියෝව (MP4) ලෙස යැවීම
      await danuwa.sendMessage(
        targetJid,
        {
          video: { url: downloadUrl },
          mimetype: "video/mp4",
          caption: `🎬 *${data.title}*\n\n> *Generated by DENETH-MD* 🚀`,
          contextInfo: newsletterContext
        },
        { quoted: mek }
      );

      return reply("✅ *Video downloaded successfully by DENETH-MD!*");
    } catch (e) {
      console.log(e);
      reply(`❌ *Error:* ${e.message || "වීඩියෝ සර්වර් එකේ පොඩි අවුලක්, පසුව උත්සාහ කරන්න!"} 😞`);
    }
  }
);
