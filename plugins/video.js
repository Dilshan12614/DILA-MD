const { cmd, commands } = require("../command");
const yts = require("yt-search");

// ==========================================
// 1. වීඩියෝ සර්ච් කර මෙනු එක යැවීමේ කොටස
// ==========================================
cmd(
  {
    pattern: "video",
    alias: ["playvideo", "ytmp4"],
    react: "🎬",
    desc: "Search YouTube videos and show download menu.",
    category: "download",
    filename: __filename,
  },
  async (
    danuwa,
    mek,
    m,
    {
      from,
      quoted,
      body,
      isCmd,
      command,
      args,
      q,
      reply,
    }
  ) => {
    try {
      if (!q) return reply("⚠️ *Please provide a video name or a YouTube link!*");

      const targetJid = typeof from === 'string' ? from : (mek.key.remoteJid || String(from));

      const search = await yts(q);
      if (!search.videos || search.videos.length === 0) {
        return reply("❌ *Video not found! Please check the name and try again.*");
      }
      
      const data = search.videos[0]; // මුල්ම වීඩියෝව නිවැරදිව තෝරාගැනීම

      // DENETH-MD ලස්සන මෙනු එක සකස් කිරීම
      let desc = `🎬 *DENETH-MD YOUTUBE DOWNLOADER*

📝 *Title:* ${data.title}
⏱️ *Duration:* ${data.timestamp}
👤 *Author:* ${data.author.name}
📌 *Views:* ${data.views.toLocaleString()}

📊 *Choose an option:*

*1.* 🎵 *Audio (MP3)*
*2.* 🎬 *Video (Playable MP4)*
*3.* 📁 *Video Document (MP4)*

💬 *Reply to this message with a number (1-3)*

> *© Powered by DENETH-MD ♡*`;

      // තම්බ්නේල් එකත් එක්ක මෙනු එක වට්සැප් එකට යැවීම
      await danuwa.sendMessage(
        targetJid,
        { image: { url: data.thumbnail }, caption: desc },
        { quoted: mek }
      );

    } catch (e) {
      console.log(e);
      reply(`❌ *Error:* ${e.message} 😞`);
    }
  }
);

// ==========================================
// 2. යූසර් දෙන 1, 2, 3 රිප්ලයි කියවන කොටස
// ==========================================
cmd(
  {
    on: "text",
    dontAddCommandList: true,
    filename: __filename,
  },
  async (danuwa, mek, m, { from, body, quoted, reply }) => {
    try {
      // මැසේජ් එක රිප්ලයි එකක්ද සහ ඒක DENETH-MD මෙනු එකක්ද කියා බැලීම
      if (!quoted || !quoted.caption || !quoted.caption.includes("DENETH-MD YOUTUBE DOWNLOADER")) return;

      const targetJid = typeof from === 'string' ? from : (mek.key.remoteJid || String(from));
      const input = body.trim();

      // මෙනු එකෙන් වීඩියෝ එකේ Title එක හොයාගැනීම
      const titleLines = quoted.caption.split("\n");
      let videoTitle = "Downloaded_File";
      for (let line of titleLines) {
        if (line.includes("Title:")) {
          videoTitle = line.replace("📝 Title:", "").trim();
          break;
        }
      }

      // ඔයා දීපු Apify Direct Download Link එක
      const downloadUrl = "https://api.apify.com/v2/key-value-stores/pU5aSo239aXkVfVuG/records/dQw4w9WgXcQ_RickAstley-NeverGonnaGiveYouUp(OfficialVideo)(4KRemaster).mp3";

      // යූසර් '1' කියා රිප්ලයි කළහොත් -> Audio (MP3) යැවීම
      if (input === "1") {
        await reply("🎵 *Downloading your Audio... Please wait!* ⏳");
        await danuwa.sendMessage(
          targetJid,
          { audio: { url: downloadUrl }, mimetype: "audio/mp4" },
          { quoted: mek }
        );
      } 
      // යූසර් '2' කියා රිප්ලයි කළහොත් -> Video (MP4) යැවීම
      else if (input === "2") {
        await reply("🎬 *Downloading your Video... Please wait!* ⏳");
        await danuwa.sendMessage(
          targetJid,
          { video: { url: downloadUrl }, mimetype: "video/mp4", caption: `🎬 ${videoTitle}\n\n> *Generated by DENETH-MD* 🚀` },
          { quoted: mek }
        );
      } 
      // යූසර් '3' කියා Rිප්ලයි කළහොත් -> Document (MP4) යැවීම
      else if (input === "3") {
        await reply("📁 *Downloading your Video Document... Please wait!* ⏳");
        await danuwa.sendMessage(
          targetJid,
          { document: { url: downloadUrl }, mimetype: "video/mp4", fileName: `${videoTitle}.mp4`, caption: `📁 ${videoTitle}\n\n> *Generated by DENETH-MD* 🚀` },
          { quoted: mek }
        );
      }

    } catch (e) {
      console.log("Reply Processor Error:", e);
    }
  }
);
